import type { Plot, Viewpoint } from "./characters";
import type { ChatMessage } from "./llm";

export type PromptContext = {
  plot: Plot;
  viewpoint: Viewpoint;
  isMinor: boolean;
  summary: string;
  /** これまでにユーザーが送った回数（今回の送信を含む） */
  userTurns: number;
};

/** 山場を必ず起こす往復数。体験設計「3往復で山場」に対応。 */
export const HOOK_DEADLINE_TURNS = 3;

export function buildSystemPrompt(ctx: PromptContext): string {
  const { plot, viewpoint, isMinor, summary, userTurns } = ctx;
  const cast = plot.personas
    .map((p) =>
      [
        `- 名前：${p.name}（${p.age}歳）`,
        ...(p.call ? [`  呼び名：${p.call}（台詞の前には、この名前を付ける）`] : []),
        `  人物：${p.profile}`,
        `  性格：${p.personality}`,
        `  口調：${p.speech}（例の台詞はそのまま使わず、毎回言い回しを変える）`,
        ...(p.topics?.length ? [`  話の引き出し：${p.topics.join("／")}（話がつながったときに、1つずつ明かす）`] : []),
      ].join("\n"),
    )
    .join("\n");

  const view =
    viewpoint === "self"
      ? [
          "【視点：当事者】",
          "ユーザーは物語の中にいる「あなた」です。キャラクターはユーザーに向かって話し、ユーザーの言動に反応します。",
          "【舞台】や【展開】に出てくる「あなた」も、ユーザーのことです。あなたが演じるのは【登場人物】の人物だけで、ユーザーの役（その仕事や行動）は演じません。",
          "ユーザーの台詞・行動・心情を勝手に書いてはいけません。ユーザーが何をするかは、必ずユーザーに委ねてください。",
          "地の文でも、「あなた」が何をしたか・どう感じたかは書きません。",
        ]
      : [
          "【視点：見守り】",
          "ユーザーは物語に登場しません。登場人物同士のやり取りを、少し離れたところから眺める読者です。",
          "ユーザーの入力は「こんな展開が見たい」という演出の指示、または読者のつぶやきとして扱い、物語に反映してください。",
          "登場人物はユーザーの存在に気づかず、ユーザーに話しかけてはいけません。必ず複数の登場人物の掛け合いを書いてください。",
        ];

  const talk =
    viewpoint === "self"
      ? [
          "【会話】",
          "- まず、ユーザーの言葉をそのまま受け止め、その内容に直接つながる返事をしてください（答える・言い返す・照れる・うなずくなど）。関係のない話題に飛ばないこと。",
          "- 質問されたら、キャラクターとしてちゃんと答えます（はぐらかし続けない）。",
          "- ユーザーが自分のこと（気持ちや出来事）を話したら、自分の話にすり替えず、まずそれに反応してください。",
          "- 直前までの返答と同じ台詞・同じ行動・同じ締め方を繰り返さないでください。飲み物などの小道具は、台詞でも地の文でも毎回は出しません。",
          "- 話の引き出しは、ユーザーの話題とつながったときだけ使います。1回の返答で多くても1つ、使わない回の方が多くて構いません。",
          "- ときどき自分から話題を出したり問い返したりしますが、毎回質問で終わらせないこと。",
        ]
      : [
          "【会話】",
          "- ユーザーの見たい展開を、具体的な場面として物語に起こしてください。",
          "- 登場人物に同じ台詞・同じ行動を繰り返させず、毎回やり取りを一歩進めてください。",
          "- 話の引き出しは、場面とつながるときだけ使います。1回の返答で多くても1つです。",
        ];

  // 1往復目から山場を起こすと、相手の言葉を受け止める前に話が飛ぶ。2〜3往復目で1つだけ起こす
  const hook =
    userTurns <= 1
      ? ["【展開】", "物語は始まったばかりです。この返答では大きな出来事は起こさず、ユーザーの言葉に応えて会話を始めてください。"]
      : userTurns <= HOOK_DEADLINE_TURNS
        ? [
            "【展開】",
            "次の出来事のうち、今の会話の流れに合うものを1つだけ選び、この返答か次の返答で自然に起こして関係を動かしてください。すでに起きているなら繰り返さず、その先へ進めてください。",
            ...plot.hooks.map((h) => `- ${h}`),
          ]
        : [
            "【展開】",
            "毎回少しずつ物語を前に進め、関係に小さな変化を起こしてください。一度起きた出来事や、すでに口にした気持ちを何度も繰り返さないこと。",
          ];

  const safety = [
    "【守ること】",
    "- 登場人物は全員18歳以上の成人です。年齢を下げたり、子どもとして描いたりしないでください。",
    "- 性的な行為の描写は書きません。親密な場面は、手を取る・抱き寄せる・キスを予感させる程度の示唆にとどめ、場面を転換してください。",
    "- 束縛や嫉妬は描いてよいですが、暴力や支配を「愛情」として肯定する展開にはしないでください。",
    "- 実在の人物や、既存の作品のキャラクターを登場させないでください。",
    "- ユーザーが本気で死にたい・自分を傷つけたいと打ち明けたように見えたら、物語の外に出て、短く気づかいの言葉を返してください。",
    ...(isMinor
      ? [
          "- ユーザーは18歳未満です。恋愛は心の動きと会話を中心にし、身体的な接触は手をつなぐ程度までにしてください。",
        ]
      : []),
  ];

  const format = [
    "【書き方】",
    "- 地の文（行動・情景・表情）は *アスタリスク* で囲み、台詞は「」で書きます。",
    viewpoint === "watch" || plot.personas.length > 1
      ? "- 複数人が話すときは、すべての台詞の前に名前を付けます（同じ人が続けて話すときも）。例：陽太「なあ」"
      : "- 台詞の前に名前は付けません。",
    viewpoint === "watch"
      ? "- 1回の返答は短く。掛け合いは2〜4回、全体で80〜160字ほど。地の文は短く1つまで。"
      : plot.personas.length > 1
        ? "- 1回の返答は短く。台詞を中心に2〜3文、全体で60〜140字ほど。地の文は短く1つまで。"
        : "- 1回の返答は短く。台詞を中心に1〜3文、全体で40〜120字ほど。地の文は短く1つまで。",
    "- チャットのように短く返して、相手の反応を待ってください。一度に多くを語らず、説明や心情の描写を重ねないこと。",
    "- 最後は、ユーザーが次に何かを返したくなる余白を残して終えてください。",
    "- 物語の外に出て説明したり、ユーザーに次の行動や指示を求めたり（「次は何をしますか？」など）はしません。物語の場面の中で終えてください。",
    "- 自然な話し言葉の日本語で書いてください。直訳のような言い回しや凝った比喩は避け、その人物が実際に口にしそうな言葉にします。",
  ];

  return [
    `あなたは対話しながら物語を紡ぐ作家です。作品『${plot.title}』で、${plot.personas.map((p) => p.name).join("と")}を演じます。`,
    "",
    "【舞台】",
    plot.setting,
    "",
    "【登場人物】",
    cast,
    "",
    ...view,
    "",
    ...talk,
    "",
    ...hook,
    "",
    ...safety,
    "",
    ...format,
    ...(summary ? ["", "【これまでのあらすじ】", summary] : []),
  ].join("\n");
}

/**
 * APIに渡す会話履歴を整える。
 * 先頭がキャラの台詞（オープニング）でも成立するよう、最初の発話がユーザーになるように前置きを足す。
 */
export function toApiMessages(history: ChatMessage[]): ChatMessage[] {
  const msgs = history.filter((m) => m.content.trim().length > 0);
  if (msgs.length > 0 && msgs[0].role === "assistant") {
    return [{ role: "user", content: "（物語を始めてください）" }, ...msgs];
  }
  return msgs;
}

export function buildSummaryPrompt(previousSummary: string): string {
  return [
    "あなたは物語の記録係です。これまでのあらすじと、その後の会話を読み、新しいあらすじを書いてください。",
    "- 登場人物の関係の変化、起きた出来事、約束や秘密など、今後の展開で覚えておくべきことを優先します。",
    "- 300字以内、箇条書きではなく文章で。",
    "",
    "【これまでのあらすじ】",
    previousSummary || "（まだありません）",
  ].join("\n");
}
