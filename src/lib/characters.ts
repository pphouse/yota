export type Viewpoint = "self" | "watch";

export type Persona = {
  name: string;
  age: number;
  profile: string; // 外見・職業・背景
  personality: string;
  speech: string; // 口調の指定と例
  /** 推し色。アイコン・吹き出し・表紙に使う */
  color: string;
  /** アイコンに入れる一文字 */
  mark: string;
};

export type Plot = {
  id: string;
  title: string;
  /** 表紙の縦書きタイトルの改行位置 */
  coverLines: string[];
  catchphrase: string;
  tags: string[];
  /** この作品で選べる視点。先頭が既定。 */
  viewpoints: Viewpoint[];
  personas: Persona[];
  /** 物語の舞台・関係性 */
  setting: string;
  /** 視点ごとの最初の一言（キャラから話しかける） */
  opening: Record<Viewpoint, string | undefined>;
  /** 最初に返しやすい選択肢 */
  starterReplies: Record<Viewpoint, string[] | undefined>;
  /** 3往復以内に起こす山場の候補 */
  hooks: string[];
  /** カードや一覧の配色（CSSのhue） */
  hue: number;
};

