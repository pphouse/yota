/** 画面で呼ぶときの名前（灰原 湊斗 → 湊斗、ライナルト・ヴァイス → ライナルト、呼び名があればそれ） */
export function callName(p: Persona): string {
  if (p.call) return p.call;
  if (p.name.includes(" ")) return p.name.split(" ").at(-1)!;
  return p.name.split("・")[0];
}
