export type Persona = {
  name: string;
  age: number;
  profile: string; // 外見・職業・背景
  personality: string;
  speech: string; // 口調の指定と例（例はモデルにそのまま繰り返させない）
  /** 推し色。名前とアイコンの縁にだけ使う */
  color: string;
  /** アイコンに入れる一文字（顔の絵がないとき） */
  mark: string;
  /** 顔の絵（正方形）。あれば一文字のアイコンの代わりに使う */
  face?: string;
  /** 話の引き出し（過去・好み・小さな秘密）。会話の流れで少しずつ明かし、同じ話題ばかりにならないようにする */
  topics?: string[];
  /** 画面や台詞の前で使う呼び名。省略すると名（灰原 湊斗 → 湊斗）。名字で呼び合う作品で使う */
  call?: string;
  /** 敬語（polite）かタメ口（plain）か。見せ場で崩れやすいので、プロンプトの最後にもう一度書く。途中で変わる人物は省く */
  register?: "polite" | "plain";
  /** 以下はプロフィール（作品の紹介ページに出し、プロンプトにも渡す） */
  /** 名前の読み（ひらがな）。カタカナの名前は省く */
  reading?: string;
  /** 身長（cm） */
  height?: number;
  likes?: string[];
  dislikes?: string[];
  /** 口癖（口調の例とは別に、ときどき出る言い回し） */
  habits?: string[];
  /** 好きになったら（関係が深まってから見せる一面） */
  inLove?: string;
};

export type Plot = {
  id: string;
  title: string;
  catchphrase: string;
  tags: string[];
  /** ホームのカテゴリ（GENRES） */
  genres: Genre[];
  /** この作品で選べる視点。先頭が既定。 */
  viewpoints: Viewpoint[];
  personas: Persona[];
  /** 物語の舞台・関係性 */
  setting: string;
  /** 視点ごとの最初の一言（キャラから話しかける） */
  opening: Record<Viewpoint, string | undefined>;
  /** 最初に返しやすい選択肢 */
  starterReplies: Record<Viewpoint, string[] | undefined>;
  /** 3往復以内に起こす山場の候補 */
  hooks: string[];
  /** カードや一覧の配色（CSSのhue） */
  hue: number;
  /** 表紙の絵（縦長）。一覧・注目作・年齢確認・名場面カードに使う */
  cover?: string;
  /** 会話画面の背景の絵（縦長） */
  backdrop?: string;
  /** ホームの「注目作」に出すか */
  featured?: boolean;
  /** 作品の紹介ページの紹介文（改行で段落を分ける） */
  intro?: string;
  /** 会話の最初に出すナレーション。見守りもある作品では「あなた」を書かない。省くと setting を出す */
  prologue?: string;
  /** 当事者視点での、あなたの役（紹介ページに出す） */
  role?: string;
};

